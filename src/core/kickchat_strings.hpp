enum Language { Spanish = 0, English = 1 };

inline std::atomic<int> &languageState() {
    static std::atomic<int> language(Spanish);
    return language;
}
inline Language currentLanguage() {
    return languageState().load(std::memory_order_relaxed) == English ? English : Spanish;
}
inline void setLanguage(Language language) {
    languageState().store(language == English ? English : Spanish, std::memory_order_relaxed);
}

